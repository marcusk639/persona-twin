"""Fix round 2 for the Claude Code connector.

Review found two real message-loss bugs on the actual corpus, plus a third
found independently while verifying the fix; a fourth item pins the paste
thresholds at their exact boundaries.

1. Partial final line (live session file mid-write) corrupted the cursor
   and permanently lost the completed message once the writer finished it.
2. source_id hashed text alone, so identical short messages ("yes",
   "fails", ...) collided and were silently dropped by the vault's
   (subject_id, source, source_id) dedup — 114/2,593 messages (4.4%) on
   the real corpus.
3. `<local-command-caveat>...</local-command-caveat>` scaffolding leaked
   through unstripped.
4. The `looks_pasted` thresholds (8000 chars, 50% fence removal) were only
   tested far past their boundaries.

These tests build their own ephemeral fixture files under tmp_path rather
than touching tests/fixtures/ or tests/fixtures_paste/, since several of
them need to mutate a file mid-test (simulating a live append) or need
exact character counts that would be fragile to encode as static fixtures.
"""
import json
from pathlib import Path
from persona_twin.config import SubjectConfig
from persona_twin.paths import SubjectPaths
from persona_twin.connectors.base import SubjectContext
from persona_twin.connectors.claude_code import ClaudeCodeConnector, _user_text


def _ctx(tmp_path):
    paths = SubjectPaths("alice", tmp_path)
    paths.ensure()
    return SubjectContext(
        config=SubjectConfig(subject_id="alice", display_name="A"), paths=paths)


# --- 1. partial final line -------------------------------------------------

def test_partial_final_line_is_not_lost_and_completes_exactly_once(tmp_path):
    src = tmp_path / "src"
    src.mkdir()
    f = src / "session.jsonl"

    first = json.dumps({"type": "user", "message": {"role": "user",
                                                      "content": "first message"}})
    second_full = json.dumps({"type": "user", "message": {"role": "user",
                                                            "content": "second message"}})
    cut = len(second_full) - 12
    partial, remainder = second_full[:cut], second_full[cut:]

    # Simulate a live session file mid-write: one complete line, then a
    # trailing fragment with no newline yet.
    f.write_text(first + "\n" + partial)

    ctx = _ctx(tmp_path)
    c = ClaudeCodeConnector(roots=[src])

    pass1 = list(c.fetch(ctx, None))
    assert [e.payload["text"] for e, _ in pass1] == ["first message"]
    cursor = pass1[-1][1]
    # The stored offset must stop right after the complete first line —
    # i.e. before the partial fragment, not at end-of-file.
    assert json.loads(cursor)[str(f)] == len(first) + 1

    # Resuming while the line is still incomplete yields nothing new.
    assert list(c.fetch(ctx, cursor)) == []

    # The writer finishes the line.
    with f.open("a") as fh:
        fh.write(remainder + "\n")

    pass2 = list(c.fetch(ctx, cursor))
    assert [e.payload["text"] for e, _ in pass2] == ["second message"]

    # The completed message was emitted exactly once overall.
    assert len(pass1) + len(pass2) == 2


# --- 2. positional source_id ------------------------------------------------

def test_identical_text_at_different_positions_gets_distinct_source_ids(tmp_path):
    src = tmp_path / "src"
    src.mkdir()
    f = src / "session.jsonl"
    line = json.dumps({"type": "user", "message": {"role": "user", "content": "yes"}})
    f.write_text((line + "\n") * 3)

    ctx = _ctx(tmp_path)
    c = ClaudeCodeConnector(roots=[src])
    ids = [e.source_id for e, _ in c.fetch(ctx, None)]

    assert len(ids) == 3
    assert len(set(ids)) == 3  # no collisions despite identical text


def test_source_ids_still_stable_across_runs_with_positional_component(tmp_path):
    src = tmp_path / "src"
    src.mkdir()
    f = src / "session.jsonl"
    line = json.dumps({"type": "user", "message": {"role": "user", "content": "yes"}})
    f.write_text((line + "\n") * 3)

    ctx = _ctx(tmp_path)
    c = ClaudeCodeConnector(roots=[src])
    first = [e.source_id for e, _ in c.fetch(ctx, None)]
    second = [e.source_id for e, _ in c.fetch(ctx, None)]
    assert first == second


# --- 3. local-command-caveat stripping -------------------------------------

def test_local_command_caveat_is_stripped(tmp_path):
    src = tmp_path / "src"
    src.mkdir()
    f = src / "session.jsonl"
    content = ("<local-command-caveat>Caveat: The messages below were "
               "generated by the user while running a local command.</local-command-caveat>"
               "please review the output")
    entry = {"type": "user", "message": {"role": "user", "content": content}}
    f.write_text(json.dumps(entry) + "\n")

    ctx = _ctx(tmp_path)
    c = ClaudeCodeConnector(roots=[src])
    texts = [e.payload["text"] for e, _ in c.fetch(ctx, None)]

    assert texts == ["please review the output"]
    assert "Caveat" not in texts[0]


# --- 4. pinned threshold boundaries (direct _user_text unit tests) --------

def test_prose_chars_exactly_8000_is_not_flagged():
    entry = {"type": "user", "message": {"role": "user", "content": "a" * 8000}}
    info = _user_text(entry)
    assert info["prose_chars"] == 8000
    assert info["looks_pasted"] is False


def test_prose_chars_8001_is_flagged():
    entry = {"type": "user", "message": {"role": "user", "content": "a" * 8001}}
    info = _user_text(entry)
    assert info["prose_chars"] == 8001
    assert info["looks_pasted"] is True


def test_exactly_half_removed_by_fence_is_not_flagged():
    prose = "p" * 10
    fence = "```" + "f" * 4 + "```"  # span length 10 == prose length 10
    entry = {"type": "user", "message": {"role": "user", "content": prose + fence}}
    info = _user_text(entry)
    assert info["raw_chars"] == 20
    assert info["prose_chars"] == 10
    assert info["looks_pasted"] is False


def test_just_over_half_removed_by_fence_is_flagged():
    prose = "p" * 10
    fence = "```" + "f" * 5 + "```"  # span length 11 > prose length 10
    entry = {"type": "user", "message": {"role": "user", "content": prose + fence}}
    info = _user_text(entry)
    assert info["raw_chars"] == 21
    assert info["prose_chars"] == 10
    assert info["looks_pasted"] is True
